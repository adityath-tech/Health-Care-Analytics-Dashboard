# 1. DATA LOADING

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

df = pd.read_csv("healthcare_dataset.csv")
print(df.head())


# 2. DATA CLEANING

print(df.isnull().sum())
print(df.duplicated().sum())

df.drop_duplicates(inplace=True)

df['Date of Admission'] = pd.to_datetime(df['Date of Admission'])
df['Discharge Date'] = pd.to_datetime(df['Discharge Date'])

df['Stay Days'] = (
    df['Discharge Date'] - df['Date of Admission']
).dt.days

print(df.isnull().sum())


# 3. DATA UNDERSTANDING

print(df.shape)
print(df.info())
print(df.describe())
print(df.columns)


# 4. DATA ANALYSIS

print(df['Billing Amount'].sum())

print(df['Billing Amount'].mean())

print(df['Age'].mean())

print(df['Name'].count())

print(df.groupby('Hospital')['Name'].count())

print(df.groupby('Medical Condition')['Name'].count())

print(df.groupby('Gender')['Name'].count())

print(df.groupby('Admission Type')['Name'].count())

print(df.groupby('Insurance Provider')['Name'].count())

print(df.groupby('Blood Type')['Name'].count())

print(df.groupby('Medication')['Name'].count())

print(df.groupby('Medical Condition')['Billing Amount'].mean())

print(df.groupby('Test Results')['Name'].count())

print(df.groupby('Hospital')['Billing Amount'].sum())


# 5. DATA VISUALIZATION







sns.histplot(df['Age'], kde=True)
plt.title("Patient Age Distribution")
plt.show()


sns.histplot(df['Billing Amount'], kde=True)
plt.title("Billing Amount Analysis")
plt.show()


sns.barplot(data=df, x='Medical Condition', y='Billing Amount')
plt.xticks(rotation=45)
plt.title("Medical Condition-wise Billing")
plt.show()


sns.histplot(df['Stay Days'], kde=True)
plt.title("Hospital Stay Analysis")
plt.show()


sns.heatmap(
    df.select_dtypes(include='number').corr(),
    cmap='coolwarm',
    annot=True
)
plt.title("Healthcare Correlation")
plt.show()


# 6. BUSINESS INSIGHTS

print("Total Patients:", df['Name'].count())

print("Total Billing:", round(df['Billing Amount'].sum(), 2))

print("Average Billing:", round(df['Billing Amount'].mean(), 2))

print("Average Age:", round(df['Age'].mean(), 2))

print("Average Stay Days:", round(df['Stay Days'].mean(), 2))

print("Most Common Medical Condition:",
      df['Medical Condition'].mode()[0])

print("Most Common Gender:",
      df['Gender'].mode()[0])

print("Most Common Admission Type:",
      df['Admission Type'].mode()[0])

print("Top Hospital:",
      df.groupby('Hospital')['Name'].count().idxmax())

print("Top Insurance Provider:",
      df.groupby('Insurance Provider')['Name'].count().idxmax())

print("Most Common Medication:",
      df['Medication'].mode()[0])